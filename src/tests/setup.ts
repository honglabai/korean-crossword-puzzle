const store: Record<string, string> = {};

const localStorageMock = {
  getItem: (key: string) => store[key] ?? null,
  setItem: (key: string, value: string) => {
    store[key] = String(value);
  },
  removeItem: (key: string) => {
    delete store[key];
  },
  clear: () => {
    for (const key of Object.keys(store)) {
      delete store[key];
    }
  },
  get length() {
    return Object.keys(store).length;
  },
  key: (index: number) => Object.keys(store)[index] ?? null,
};

// Assign to globalThis and window
(globalThis as unknown as { localStorage: Storage }).localStorage = localStorageMock as unknown as Storage;
if (typeof window !== 'undefined') {
  (window as unknown as { localStorage: Storage }).localStorage = localStorageMock as unknown as Storage;
}
