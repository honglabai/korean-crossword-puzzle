export function getWordContext(term: string, fallbackDef: string, category?: CategoryId): string {
  if (ENRICHED_CONTEXTS[term]) {
    return ENRICHED_CONTEXTS[term];
  }

  // Smart domain-tailored contextual background
  switch (category) {
    case 'POLITICS':
      return `[헌법 및 정치학 상식] '${term}'은(는) 입법 과정, 선거 제도 및 민주주의 통치 질서에서 필수적인 핵심 개념입니다.`;
    case 'SOCIETY':
      return `[현대 사회·시사 해설] '${term}'은(는) 시민 공동체의 권익 증진, 사회적 갈등 조정 및 복지 제도 발전에 중요한 역할을 하는 시사 용어입니다.`;
    case 'CULTURE':
      return `[문화 인류학 해설] '${term}'은(는) 전통과 현대 대중문화의 교류 및 인류 문화유산의 보존에 뜻깊은 의의를 지닌 주요 개념입니다.`;
    case 'SPORTS':
      return `[스포츠 과학·규칙 상식] '${term}'은(는) 경기 전략 전술, 공정한 페어플레이 및 스포츠맨십 구현의 핵심적인 경기 규칙/요소입니다.`;
    case 'KOREAN_HISTORY':
      return `[한국사 역사적 맥락] '${term}'은(는) 고대부터 근현대에 이르기까지 우리 민족의 국가 발전과 국난 극복, 찬란한 문화 융성을 증명하는 중요한 역사적 키워드입니다.`;
    case 'WORLD_HISTORY':
      return `[세계사 문명사적 의의] '${term}'은(는) 인류 문명의 동서 교류, 대혁명 및 글로벌 국제질서 형성 과정에서 중대한 획을 그은 사건/제도입니다.`;
    case 'MUSIC':
      return `[음악 이론 및 감상 해설] '${term}'은(는) 동서양 악기의 음향 구조, 악곡의 형식미와 예술적 감동을 직조하는 필수 음악 용어입니다.`;
    case 'ART':
      return `[미술사 및 조형 예술 해설] '${term}'은(는) 회화, 조각, 현대 시각 예술의 기법과 미학적 패러다임 전환을 이끈 핵심 조형 개념입니다.`;
    default:
      return `[심층 시사 상식] ${fallbackDef} 해당 분야의 학술 및 실전 상식에서 매우 빈번하게 다뤄지는 핵심 개념입니다.`;
  }
}

// Backward compatibility alias for political context
export function getPoliticalContext(term: string, fallbackDef: string): string {
  return getWordContext(term, fallbackDef, 'POLITICS');
}
